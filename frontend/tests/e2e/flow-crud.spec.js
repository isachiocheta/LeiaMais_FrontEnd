import { test, expect } from '@playwright/test';
import { api, confirm, dates, login, open, unique } from './support.js';

test('CRUD real de livros, ciclos e encontros, transições e conflito de negócio', async ({ page, context }) => {
  await login(page);
  const title = unique('Livro descartável');
  await open(page, '/admin/livros/novo');
  await page.getByRole('textbox', { name: 'Título', exact: true }).fill(title);
  await page.getByRole('textbox', { name: 'Autor', exact: true }).fill('Autoria descartável');
  await page.getByRole('combobox', { name: /^Gênero/ }).selectOption({ index: 1 });
  await page.getByRole('spinbutton', { name: 'Total de páginas', exact: true }).fill('240');
  await page.getByRole('button', { name: 'Cadastrar livro', exact: true }).click();
  await expect(page).toHaveURL(/admin\/livros$/);
  const book = (await api(context, `livros?q=${encodeURIComponent(title)}`)).data[0]; expect(book.titulo).toBe(title);
  await open(page, `/admin/livros/${book.id}/editar`);
  await page.getByRole('textbox', { name: 'Descrição (opcional)', exact: true }).fill('Descrição alterada e persistida.');
  await page.getByRole('button', { name: 'Salvar alterações', exact: true }).click();
  await open(page, `/catalogo/${book.id}`); await page.reload(); await expect(page.locator('main')).toContainText('Descrição alterada e persistida.');
  const cycleName = unique('Ciclo descartável'), period = dates();
  await open(page, '/admin/ciclos/novo');
  await page.getByRole('textbox', { name: 'Nome do ciclo', exact: true }).fill(cycleName);
  await page.getByRole('button', { name: 'Escolher livro', exact: true }).click();
  const picker = page.getByRole('dialog');
  await picker.getByRole('textbox', { name: 'Buscar livro por título ou autor', exact: true }).fill(title);
  await picker.getByRole('button', { name: `Selecionar ${title}`, exact: true }).click();
  await page.getByLabel(/^Data inicial/).fill(period.start); await page.getByLabel(/^Data final/).fill(period.end);
  await page.getByRole('button', { name: 'Criar ciclo', exact: true }).click();
  await expect(page).toHaveURL(/\/ciclos\/\d+$/); const cycleId = page.url().split('/').pop();
  await page.getByRole('link', { name: 'Editar ciclo', exact: true }).click();
  await page.getByRole('textbox', { name: 'Orientações (opcional)', exact: true }).fill('Orientação atualizada.\nSegunda linha segura.');
  await page.getByRole('button', { name: 'Salvar alterações', exact: true }).click();
  await expect(page.locator('main')).toContainText('Orientação atualizada.');
  await page.getByRole('button', { name: 'Iniciar ciclo', exact: true }).click(); await confirm(page, 'Iniciar ciclo');
  await expect(page.getByRole('dialog')).toHaveCount(0); await expect(page.getByRole('button', { name: 'Concluir ciclo', exact: true })).toBeVisible();
  const meetingTitle = unique('Encontro descartável');
  await open(page, `/admin/encontros/novo?cicloId=${cycleId}`);
  await page.getByRole('button', { name: 'Escolher ciclo', exact: true }).click();
  await page.getByRole('dialog').getByRole('textbox').fill(cycleName);
  await page.getByRole('dialog').getByRole('button', { name: `Selecionar ${cycleName}`, exact: true }).click();
  await page.getByRole('textbox', { name: 'Título do encontro', exact: true }).fill(meetingTitle);
  await page.getByLabel(/^Data e horário em São Paulo/).fill(period.future);
  await page.getByRole('textbox', { name: 'Local', exact: true }).fill('Sala de teste');
  await page.getByRole('button', { name: 'Criar encontro', exact: true }).click();
  await expect(page).toHaveURL(/\/encontros\/\d+(?:\?.*)?$/); const meetingId = new URL(page.url()).pathname.split('/').pop();
  expect(Math.floor(Date.parse((await api(context, `encontros/${meetingId}`)).data.inicioEm) / 60000)).toBe(Math.floor(Date.parse(period.iso) / 60000));
  await page.getByRole('link', { name: 'Editar encontro', exact: true }).click();
  await page.getByRole('textbox', { name: 'Local', exact: true }).fill('Local corrigido');
  await page.getByRole('button', { name: 'Salvar alterações', exact: true }).click();
  await expect(page.locator('main')).toContainText('Local corrigido'); await page.reload(); await expect(page.locator('main')).toContainText('Local corrigido');
  await open(page, `/ciclos/${cycleId}`);
  await page.getByRole('button', { name: 'Concluir ciclo', exact: true }).click(); await confirm(page, 'Concluir ciclo');
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText(/agendad|conflito/i);
  await page.getByRole('dialog').getByRole('button', { name: 'Cancelar', exact: true }).click();
  await open(page, `/encontros/${meetingId}`);
  await page.getByRole('button', { name: 'Cancelar encontro', exact: true }).click(); await confirm(page, 'Cancelar encontro');
  await expect(page.getByRole('dialog')).toHaveCount(0); await expect(page.locator('main')).toContainText('Cancelado');
  await page.getByRole('button', { name: 'Excluir encontro', exact: true }).click(); await confirm(page, 'Excluir encontro');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  expect((await api(context, `encontros/${meetingId}`, { status: 404 })).error.code).toBe('NOT_FOUND');
  await open(page, `/ciclos/${cycleId}`);
  await page.getByRole('button', { name: 'Concluir ciclo', exact: true }).click(); await confirm(page, 'Concluir ciclo'); await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button', { name: 'Excluir ciclo', exact: true }).click(); await confirm(page, 'Excluir ciclo');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await api(context, `ciclos/${cycleId}`, { status: 404 });
  await open(page, `/admin/livros?q=${encodeURIComponent(title)}`);
  await page.getByRole('button', { name: `Excluir ${title}`, exact: true }).click(); await confirm(page, 'Excluir livro');
  await expect(page.getByRole('dialog')).toHaveCount(0); await api(context, `livros/${book.id}`, { status: 404 });
});

